#!/usr/bin/env python3
"""Generates the Caliper benchmark file for ONE step of an experiment: a short warm-up round followed
by the measured round, both running the same workload at a fixed rate.

Update workloads walk each record through OPEN -> UNDER_REVIEW -> CLOSED, so a record accepts two updates;
the number of records to seed is derived from the rate, the duration and the number of workers.
"""
import argparse
import json
import math

MODULES = {
    "insert": "workloads/insertDiagnostic.js",
    "read": "workloads/readDiagnostic.js",
    "update": "workloads/updateDiagnostic.js",
    "history": "workloads/getHistory.js",
    "mixed": "workloads/mixedWorkload.js",
}


def per_worker(tps, duration, workers):
    return math.ceil(tps * duration / workers)


def workload_args(op, tps, duration, workers, arrivals):
    """Arguments for the workload module. With Poisson arrivals the number of transactions per worker varies,
    so the pools of records that updates consume get a margin of four standard deviations."""
    n = per_worker(tps, duration, workers)
    n_max = n + (4 * math.sqrt(n) + 5 if arrivals == "poisson" else 0)
    args = {}
    if op == "read":
        args["records"] = 50
    elif op == "history":
        args["records"] = 20
    elif op == "update":
        args["records"] = math.ceil(n_max / 2) + 2
    elif op == "mixed":
        # slot 8 of every 10 transactions is an update
        args.update(readRecords=20, updateRecords=math.ceil(n_max * 0.1 / 2) + 3)
    return args


def round_yaml(label, op, tps, duration, workers, arrivals):
    args = workload_args(op, tps, duration, workers, arrivals)
    rate_type = "./rate/poissonRate.js" if arrivals == "poisson" else "fixed-rate"
    lines = [
        f"    - label: {label}",
        f"      txDuration: {duration}",
        "      rateControl:",
        f"        type: {rate_type}",
        "        opts:",
        f"          tps: {tps}",
        "      workload:",
        f"        module: {MODULES[op]}",
    ]
    if args:
        lines.append("        arguments:")
        lines += [f"          {k}: {v}" for k, v in args.items()]
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--op", required=True, choices=MODULES)
    p.add_argument("--tps", required=True, type=float)
    p.add_argument("--duration", required=True, type=int, help="measured round, seconds")
    p.add_argument("--workers", required=True, type=int)
    p.add_argument("--arrivals", choices=("poisson", "fixed"), default="poisson",
                   help="arrival process: independent Poisson arrivals (default) or Caliper fixed-rate")
    p.add_argument("--warmup-tps", type=float, default=None)
    p.add_argument("--warmup-duration", type=int, default=10)
    p.add_argument("--out", required=True, help="benchmark YAML to write")
    p.add_argument("--meta", required=True, help="meta JSON to write")
    a = p.parse_args()

    warm_tps = a.warmup_tps if a.warmup_tps is not None else min(a.tps, 5)
    tps = int(a.tps) if a.tps == int(a.tps) else a.tps
    warm = int(warm_tps) if warm_tps == int(warm_tps) else warm_tps

    yaml = "\n".join([
        f"# generated by gen_config.py: {a.op} at {tps} TPS for {a.duration}s, {a.workers} workers, {a.arrivals} arrivals",
        "test:",
        f"  name: step-{a.op}-{tps}tps",
        "  workers:",
        f"    number: {a.workers}",
        "  rounds:",
        round_yaml("warmup", a.op, warm, a.warmup_duration, a.workers, a.arrivals),
        "",
        round_yaml(f"step-{a.op}-{tps}", a.op, tps, a.duration, a.workers, a.arrivals),
        "",
    ])
    with open(a.out, "w") as f:
        f.write(yaml)

    meta = {
        "op": a.op,
        "tps": tps,
        "duration": a.duration,
        "workers": a.workers,
        "arrivals": a.arrivals,
        "rounds": [
            {"index": 0, "label": "warmup", "tps": warm, "duration": a.warmup_duration, "warmup": True},
            {"index": 1, "label": f"step-{a.op}-{tps}", "tps": tps, "duration": a.duration, "warmup": False},
        ],
    }
    with open(a.meta, "w") as f:
        json.dump(meta, f, indent=2)


if __name__ == "__main__":
    main()
